#!/usr/bin/env python3
"""Generate edi/segments_gen.go from the reference Java segment classes.

The segment tables (element name, padding class, declared width, description,
literal default) are the wire contract. They are transcribed mechanically from
the decompiled trama.SubTrama_* sources of
pe.gob.susalud:jr-acreditacion-susalud-logic:1.0.0 so that no width is ever
retyped by hand.

Run:  python3 -I tools/gen_segments.py
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_GLOB = os.path.join(ROOT, "_rea_work", "src", "pe", "gob", "susalud", "jr",
                        "transaccion", "susalud", "trama", "SubTrama_*.java")
DST = os.path.join(ROOT, "edi", "segments_gen.go")

ATTR_RE = re.compile(r"campoSubTrama\[(\d+)\]\.(\w+)\s*=\s*(.+?);")
LITERAL_RE = re.compile(r'^"((?:[^"\\]|\\.)*)"$')
ESCAPES = {"n": "\n", "t": "\t", "r": "\r", '"': '"', "\\": "\\", "'": "'"}


def unescape_java(s):
    """Decode the body of a Java string literal (without the quotes)."""
    out = []
    i = 0
    while i < len(s):
        ch = s[i]
        if ch != "\\":
            out.append(ch)
            i += 1
            continue
        nxt = s[i + 1]
        if nxt == "u":
            out.append(chr(int(s[i + 2:i + 6], 16)))
            i += 6
            continue
        out.append(ESCAPES.get(nxt, nxt))
        i += 2
    return "".join(out)


def literal(value):
    """Return the string value of a Java literal, or None for an expression."""
    m = LITERAL_RE.match(value.strip())
    return unescape_java(m.group(1)) if m else None


def go_string(s):
    out = ['"']
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        elif ord(ch) <= 0xFFFF:
            out.append("\\u%04x" % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def extract(path):
    seg = os.path.basename(path)[len("SubTrama_"):-len(".java")]
    src = open(path, encoding="utf-8").read()
    m = re.search(r"num_CamposSubTrama\s*=\s*(\d+)", src)
    if not m:
        raise SystemExit("no num_CamposSubTrama in " + path)
    count = int(m.group(1))

    rows = {}
    for match in ATTR_RE.finditer(src):
        idx, key, raw = int(match.group(1)), match.group(2), match.group(3)
        rows.setdefault(idx, {})[key] = raw

    fields = []
    for i in range(count):
        r = rows.get(i, {})
        name = literal(r.get("nombre", "")) or ""
        if not name:
            raise SystemExit("%s: element %d has no name" % (seg, i))
        kind = literal(r.get("atributo", "")) or ""
        fields.append({
            "name": name,
            "kind": kind,
            "min": int(r.get("longitudmin", "0").strip()),
            "max": int(r.get("longitudmax", "0").strip()),
            "desc": literal(r.get("descripcion", "")) or "",
            "default": literal(r.get("contenido", "")),
        })
    return seg, fields


KINDS = {"Numerico": "KindNumeric", "Alfanumerico": "KindAlpha"}


# Declared by the reference implementation but unreachable: SubTrama_SV1 and
# SubTrama_SV2 are never instantiated anywhere in the jar, and SV2 declares two
# elements while defining only the first (encoding it would NPE).
UNUSED = {"SV1", "SV2"}


def main():
    segs = {}
    skipped = []
    for path in sorted(glob.glob(SRC_GLOB)):
        try:
            seg, fields = extract(path)
        except SystemExit as exc:
            skipped.append(str(exc))
            continue
        if seg in UNUSED:
            skipped.append("%s: unused by the reference implementation" % seg)
            continue
        segs[seg] = fields
    names = sorted(segs)

    out = [
        "// Code generated by tools/gen_segments.py; DO NOT EDIT.",
        "//",
        "// Segment tables transcribed from the reference Java library",
        "// pe.gob.susalud:jr-acreditacion-susalud-logic:1.0.0 (trama.SubTrama_*).",
        "// Declared widths and padding classes are the wire contract.",
        "",
        "package edi",
        "",
    ]

    for name in names:
        out.append("// Seg%s is the %s segment." % (name, name))
        out.append("var Seg%s = &SegmentDef{" % name)
        out.append("\tName: %s," % go_string(name))
        out.append("\tFields: []FieldDef{")
        for f in segs[name]:
            parts = [
                "Name: %s" % go_string(f["name"]),
                "Kind: %s" % KINDS.get(f["kind"], "KindRaw"),
                "Min: %d" % f["min"],
                "Max: %d" % f["max"],
            ]
            if f["desc"]:
                parts.append("Desc: %s" % go_string(f["desc"]))
            if f["default"]:
                parts.append("Default: %s" % go_string(f["default"]))
            out.append("\t\t{%s}," % ", ".join(parts))
        out.append("\t},")
        out.append("}")
        out.append("")

    out.append("// Segments indexes every defined segment by its X12 segment ID.")
    out.append("var Segments = map[string]*SegmentDef{")
    for name in names:
        out.append('\t%s: Seg%s,' % (go_string(name), name))
    out.append("}")
    out.append("")
    out.append("func init() {")
    out.append("\tfor _, d := range Segments {")
    out.append('\t\td.Prefix = d.Name + "*"')
    out.append('\t\td.Suffix = "~"')
    out.append("\t}")
    out.append("}")
    out.append("")

    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))

    total = sum(len(v) for v in segs.values())
    print("wrote %s: %d segments, %d elements" % (DST, len(names), total))


if __name__ == "__main__":
    main()
