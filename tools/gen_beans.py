#!/usr/bin/env python3
"""Generate x12n/beans_gen.go from the reference Java bean classes.

Each bean becomes a Go struct with the same field names and order as the
reference class. Field types map String -> string, Integer -> int and
ArrayList<T> -> []*T.

Run:  python3 -I tools/gen_beans.py
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_GLOB = os.path.join(ROOT, "_rea_work", "src", "pe", "gob", "susalud", "jr",
                        "transaccion", "susalud", "bean", "*.java")
DST = os.path.join(ROOT, "x12n", "beans_gen.go")

FIELD_RE = re.compile(r"^\s*private\s+([\w.<>]+)\s+(\w+)\s*(?:=\s*[^;]+)?;", re.M)
LIST_RE = re.compile(r"ArrayList<(\w+)>")
SCALARS = {"String": "string", "Integer": "int", "Integer ": "int", "int": "int"}


def go_type(java):
    m = LIST_RE.search(java)
    if m:
        return "[]*" + m.group(1)
    return SCALARS.get(java, "string")


def go_name(java):
    return java[0].upper() + java[1:]


def main():
    out = [
        "// Code generated by tools/gen_beans.py; DO NOT EDIT.",
        "//",
        "// Data model transcribed from the reference Java library",
        "// pe.gob.susalud:jr-acreditacion-susalud-logic:1.0.0 (bean.*).",
        "",
        "package x12n",
        "",
    ]

    count = 0
    fields_total = 0
    for path in sorted(glob.glob(SRC_GLOB)):
        name = os.path.basename(path)[:-len(".java")]
        src = open(path, encoding="utf-8").read()
        fields = FIELD_RE.findall(src)
        if not fields:
            continue
        out.append("// %s mirrors bean.%s." % (name, name))
        out.append("type %s struct {" % name)
        for jtype, jname in fields:
            out.append("\t%s %s" % (go_name(jname), go_type(jtype)))
        out.append("}")
        out.append("")
        count += 1
        fields_total += len(fields)

    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print("wrote %s: %d structs, %d fields" % (DST, count, fields_total))


if __name__ == "__main__":
    main()
